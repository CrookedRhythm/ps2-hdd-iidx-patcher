"""End-to-end tests on a synthetic PS2 drive (no real game data needed).

    pip install pycdlib
    python tests/test_tools.py

Checks that what the HDD tools write is byte-for-byte what the upstream patch480p.py produces,
that switching variants and restoring backups work, and that unsafe games are left alone.
"""
import filecmp
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, "vendor", "iidx-ps2-480p")
PY = sys.executable
sys.path.insert(0, ROOT)
import ps2_hdd_patcher as hdd  # noqa: E402

failures = []


def run(*args, ok=True):
    r = subprocess.run([PY] + list(args), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if ok and r.returncode != 0:
        raise AssertionError("command failed: %s\n%s" % (" ".join(args), r.stdout))
    return r.stdout


def check(name, cond):
    print("%-60s %s" % (name, "ok" if cond else "FAIL"))
    if not cond:
        failures.append(name)


def elf_on_drive(img, startup):
    dev, games, _ = hdd.open_target(img)
    try:
        g = [g for g in games if g.startup == startup][0]
        off, size = hdd.iso_find(dev, g, [startup])
        return g.read(dev, off, size)
    finally:
        dev.close()


def reference(tmp, startup, flag=()):
    src = os.path.join(tmp, startup)
    shutil.copy(os.path.join(tmp, startup + ".elf"), src)
    out = os.path.join(tmp, "ref_%s%s" % (startup, "_480" if flag else ""))
    run(os.path.join(VENDOR, "patch480p.py"), "elf", src, out, *flag)
    with open(out, "rb") as f:
        return f.read()


def main():
    tmp = tempfile.mkdtemp(prefix="ps2hdd_test_")
    try:
        run(os.path.join(ROOT, "tests", "make_test_drive.py"), VENDOR, tmp)
        os.chdir(tmp)
        img, pristine = "ps2disk.img", "pristine.img"
        shutil.copy(img, pristine)
        tool = os.path.join(ROOT, "iidx480p_hdd.py")
        patched_ids = ["SLPM_551.17", "SLPM_552.21", "SLPM_668.28"]

        out = run(tool, "list", img)
        check("list: clean games show as original", out.count("original (480i)") == 3)
        check("list: modified game is flagged", "modified by something else" in out)

        out = run(tool, "patch", img, "--all", "--write", "--yes", "--backup", "step1.ps2bak")
        check("patch --all: modified game skipped", "skipped" in out and "SLPM_669.95" in out)
        for sid in patched_ids:
            check("448 lines: %s matches patch480p.py" % sid, elf_on_drive(img, sid) == reference(tmp, sid))

        run(tool, "patch", img, "--game", "SLPM_551.17", "--480", "--write", "--yes", "--backup", "step2.ps2bak")
        check("switch to --480: matches patch480p.py --480",
              elf_on_drive(img, "SLPM_551.17") == reference(tmp, "SLPM_551.17", ("--480",)))

        run(tool, "restore", img, "step2.ps2bak", "--write", "--yes")
        for sid in patched_ids:
            run(tool, "restore", img, "step1_%s.ps2bak" % sid, "--write", "--yes")
        check("restore: drive identical to original", filecmp.cmp(img, pristine, shallow=False))

        shutil.copy("SLPM_551.17.iso", "mine.iso")
        shutil.copy("SLPM_551.17.iso", "theirs.iso")
        run(tool, "patch", "mine.iso", "--480", "--write", "--yes", "--backup", "iso.ps2bak")
        run(os.path.join(VENDOR, "patch480p.py"), "iso", "theirs.iso", "--480")
        check("plain ISO: matches patch480p.py iso", filecmp.cmp("mine.iso", "theirs.iso", shallow=False))

        # Generic .pnach path of ps2_hdd_patcher.py, using pnach files generated by upstream.
        run(os.path.join(VENDOR, "patch480p.py"), "pnach", "pn")
        pn = os.path.join("pn", "SLPM-55221_44111A43.pnach")
        run(os.path.join(ROOT, "ps2_hdd_patcher.py"), "pnach", img, pn, "--game", "SLPM_552.21",
            "--group", "480p", "--force", "--write", "--yes", "--backup", "pn.ps2bak")
        check("pnach [480p] on drive: matches patch480p.py",
              elf_on_drive(img, "SLPM_552.21") == reference(tmp, "SLPM_552.21"))
        run(os.path.join(ROOT, "ps2_hdd_patcher.py"), "restore", img, "pn.ps2bak", "--write", "--yes")
        check("pnach restore: drive identical to original", filecmp.cmp(img, pristine, shallow=False))
    finally:
        os.chdir(ROOT)
        shutil.rmtree(tmp, ignore_errors=True)

    print("\n%s" % ("ALL TESTS PASSED" if not failures else "%d FAILED" % len(failures)))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
